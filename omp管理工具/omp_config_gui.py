    def _ok_dialog(self, dlg, value):
        dlg.result = value
        dlg.destroy()

    def _ok_numeric(self, dlg, var, val_type):
        try:
            val = val_type(var.get())
            dlg.result = val
            dlg.destroy()
        except ValueError:
            messagebox.showwarning("提示", "请输入有效的数值")

    def _ok_json(self, dlg, text_widget):
        try:
            val = json.loads(text_widget.get("1.0", tk.END).strip())
            dlg.result = val
            dlg.destroy()
        except json.JSONDecodeError:
            messagebox.showwarning("提示", "JSON 格式不正确")

    def save_all(self):
        if not self.modified_keys:
            self.save_status.set("没有需要保存的修改")
            return
        msg = "确定保存 {} 项修改？\n\n重启 OMP 后生效".format(len(self.modified_keys))
        ok = messagebox.askyesno("确认", msg)
        if not ok:
            return
        saved = 0
        errors = []
        for key in self.modified_keys:
            success, err = set_omp_config(key, self.config[key])
            if success:
                saved += 1
            else:
                errors.append("{}: {}".format(key, err))
        self.modified_keys.clear()
        if errors:
            messagebox.showwarning("部分保存失败", "\n".join(errors))
        self.save_status.set("已保存 {}/{} 项".format(saved, len(self.config)))

