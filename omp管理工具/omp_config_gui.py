    def load_config(self):
        self.config, self._raw_config, err = get_omp_config()
        if err:
            messagebox.showerror("错误", "读取 OMP 配置失败:\n{}".format(err))
            return
        for item in self.cat_tree.get_children():
            self.cat_tree.delete(item)
        for cat in CATEGORY_GROUPS:
            self.cat_tree.insert("", tk.END, iid=cat, text=cat)
        self._show_all()
        self.cat_tree.selection_set(" 所有配置")
    def _on_category_select(self, event):
        sel = self.cat_tree.selection()
        if not sel:
            return
        cat = sel[0]
        if cat == " 所有配置":
            self._show_all()
        else:
            keys = CATEGORY_GROUPS.get(cat)
            if keys:
                self._show_keys(keys)

    def _show_all(self):
        self._show_keys(sorted(self.config.keys()))

    def _show_keys(self, keys):
        for item in self.tree.get_children():
            self.tree.delete(item)
        for key in keys:
            if key not in self.config:
                continue
            value = self.config[key]
            desc = CONFIG_DESC_ZH.get(key, "")
            if isinstance(value, bool):
                val_str = "✅ 已启用" if value else " 已禁用"
                edit_str = " 点击切换"
            elif isinstance(value, (int, float)):
                val_str = str(value)
                edit_str = " 点击编辑"
            elif isinstance(value, (list, dict)):
                val_str = json.dumps(value, ensure_ascii=False)[:25]
                edit_str = " 点击编辑"
            else:
                val_str = str(value)[:25]
                edit_str = " 点击编辑"
            self.tree.insert("", tk.END, iid=key, values=(key, desc, val_str, edit_str))

    def _on_search(self, *args):
        q = self.search_var.get().strip().lower()
        if not q:
            self._show_all()
            return
        results = [k for k in sorted(self.config.keys())
                   if q in k.lower() or q in CONFIG_DESC_ZH.get(k, "").lower()]
        self._show_keys(results)

    def _on_double_click(self, event):
        sel = self.tree.selection()
        if not sel:
            return
        key = sel[0]
        value = self.config[key]
        new_val = self._edit_dialog(key, value)
        if new_val is not None:
            self.config[key] = new_val
            self.modified_keys.add(key)
            self._show_keys(sorted(self.config.keys()))

